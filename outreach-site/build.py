def find_chrome():
    env = os.environ.get("CHROME_PATH")
    candidates = [env] if env else []
    candidates += [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        shutil.which("google-chrome") or "", shutil.which("chromium") or "",
        shutil.which("chromium-browser") or "", "/opt/pw-browsers/chromium",
    ]
    pw = Path("/opt/pw-browsers")
    if pw.exists():
        candidates += [str(p) for p in sorted(pw.glob("chromium-*/chrome-linux/chrome"))]
    for c in candidates:
        if c and Path(c).is_file() and os.access(c, os.X_OK):
            return c
    return None


def chrome_run(chrome, args):
    base = [chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run",
            "--no-default-browser-check", "--virtual-time-budget=8000", "--run-all-compositor-stages-before-draw"]
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        base.append("--no-sandbox")
    res = subprocess.run(base + args, capture_output=True, text=True, timeout=180)
    if res.returncode != 0:
        raise BuildError("Chrome failed: " + (res.stderr or res.stdout)[-800:])


def crop_png(path, height):
    """Keep the top `height` rows of a PNG (stdlib only). Chrome's new headless mode
    reserves ~87px of phantom browser UI, so share images are rendered in a taller
    window and cropped back to 630px here."""
    import struct
    import zlib
    data = Path(path).read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise BuildError(f"{path} is not a PNG")
    pos, chunks = 8, []
    while pos < len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        ctype = data[pos + 4:pos + 8]
        chunks.append((ctype, data[pos + 8:pos + 8 + length]))
        pos += 12 + length
    ihdr = chunks[0][1]
    width, old_h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", ihdr)
    if interlace or depth != 8 or color not in (2, 6) or height > old_h:
        raise BuildError(f"{path}: unexpected PNG format for cropping")
    stride = 1 + width * (4 if color == 6 else 3)
    raw = zlib.decompress(b"".join(c for t, c in chunks if t == b"IDAT"))
    body = zlib.compress(raw[:stride * height], 9)

    def chunk(ctype, payload):
        return (struct.pack(">I", len(payload)) + ctype + payload
                + struct.pack(">I", zlib.crc32(ctype + payload) & 0xFFFFFFFF))
    out = data[:8] + chunk(b"IHDR", struct.pack(">II", width, height) + ihdr[8:])
    for ctype, payload in chunks[1:]:
        if ctype not in (b"IDAT", b"IEND"):
            out += chunk(ctype, payload)
    out += chunk(b"IDAT", body) + chunk(b"IEND", b"")
    Path(path).write_bytes(out)


def render_assets(build):
    """PDFs and share images, rendered by headless Chrome from generated print/OG pages."""
    chrome = find_chrome()
    if not chrome:
        raise BuildError("--assets needs Chrome or Chromium. Set CHROME_PATH=/path/to/chrome.")
    import assets as asset_templates  # templates/assets.py, kept separate to keep this file readable
    work = Path(tempfile.mkdtemp(prefix="outreach-assets-"))
    try:
        jobs = asset_templates.jobs(build, work)
        for job in jobs:
            out = PUBLIC / job["out"]
            out.parent.mkdir(parents=True, exist_ok=True)
            if job["kind"] == "pdf":
                chrome_run(chrome, ["--no-pdf-header-footer", f"--print-to-pdf={out}", job["url"]])
            elif job["kind"] == "png":
                chrome_run(chrome, ["--window-size=1200,900", "--force-device-scale-factor=1",
                                    f"--screenshot={out}", job["url"]])
                crop_png(out, 630)
            elif job["kind"] == "text":
                out.write_text(job["text"], "utf-8")
            print(f"  asset  {job['out']}")
    finally:
        shutil.rmtree(work, ignore_errors=True)



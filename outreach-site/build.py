    # checks -----------------------------------------------------------------------
    def check_links(self):
        """Every internal href/src must point at a file this build produced or one in public/,
        and every #fragment must exist on its target page."""
        ids, problems = {}, []
        for rel in self.written:
            if rel.endswith(".html"):
                ids[rel] = set(re.findall(r'\sid="([^"]+)"', (self.out / rel).read_text("utf-8")))
        for rel in self.written:
            if not rel.endswith(".html"):
                continue
            text = (self.out / rel).read_text("utf-8")
            for ref in re.findall(r'\s(?:href|src)="([^"]+)"', text):
                if ref.startswith(("http:", "https:", "mailto:", "data:", "tel:")):
                    continue
                path, _, frag = ref.partition("#")
                path = path.split("?")[0]
                if self.preview:
                    target = os.path.normpath(os.path.join(os.path.dirname(rel), path)) if path else rel
                else:
                    target = (path.lstrip("/") + ("index.html" if path.endswith("/") else "")) if path else rel
                exists = target in ids or (self.out / target).exists() or (PUBLIC / target).exists()
                if not exists and target.startswith("downloads/"):
                    self.warnings.append(f"{rel}: {ref} does not exist yet (run `python3 build.py --assets`)")
                elif not exists:
                    problems.append(f"{rel}: broken link {ref}")
                elif frag and target in ids and frag not in ids[target]:
                    problems.append(f"{rel}: #{frag} not found on {target}")
        if problems:
            raise BuildError("link check failed:\n  " + "\n  ".join(sorted(set(problems))))


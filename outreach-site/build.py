# ---------------------------------------------------------------------- data
TOKEN_RE = re.compile(r"\{\{\s*([a-z_]+)(?:\.([a-z]+))?\s*\}\}")


def load_data():
    stats = json.loads((DATA / "stats.json").read_text("utf-8"))
    site = json.loads((DATA / "site.json").read_text("utf-8"))
    tokens = {}
    for section in ("audit", "method"):
        for key, entry in stats[section].items():
            if key.startswith("_"):
                continue
            if key in tokens:
                raise BuildError(f"stats.json: duplicate key '{key}'")
            tokens[key] = entry
    window = stats["method"]["window_days"]["value"]
    if not any(b.get("max_days") == window for b in stats["scorer"]["timing"]):
        raise BuildError(
            f"stats.json: scorer.timing has no band ending at window_days ({window}). "
            "Update the timing bands so one of them ends where the window ends.")
    return stats, site, tokens


def resolve_tokens(text, tokens, where):
    def sub(m):
        key, field = m.group(1), m.group(2) or "display"
        if key not in tokens:
            raise BuildError(f"{where}: unknown stat token {{{{{key}}}}}")
        if field not in tokens[key]:
            raise BuildError(f"{where}: stat '{key}' has no '{field}' field")
        return str(tokens[key][field])
    return TOKEN_RE.sub(sub, text)


def lint_hardcoded(text, tokens, where):
    """Numbers from stats.json must be referenced, never typed into content."""
    problems = []
    bare = TOKEN_RE.sub(" ", text)
    for key, entry in tokens.items():
        shown = str(entry.get("display", ""))
        if not re.search(r"\d", shown) or shown in ("0", "1"):
            continue
        tail = r"(?![\w])" if shown[-1].isalnum() else ""
        for m in re.finditer(r"(?<![\w.])" + re.escape(shown) + tail, bare):
            line = bare.count("\n", 0, m.start()) + 1
            problems.append(f'{where}:{line}: "{shown}" is hardcoded. Use {{{{{key}}}}} from data/stats.json.')
    return problems


def parse_front_matter(text, where):
    if not text.startswith("---\n"):
        raise BuildError(f"{where}: missing front matter")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise BuildError(f"{where}: unterminated front matter")
    meta = {}
    for line in text[4:end].split("\n"):
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise BuildError(f"{where}: bad front matter line: {line!r}")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[key.strip()] = value
    return meta, text[end + 5:]


def word_count(md):
    text = "\n".join(l for l in md.split("\n") if not re.match(r"^\s*:{3,}", l))
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[#>*`_]", " ", text)
    return sum(1 for w in text.split() if re.search(r"\w", w))


# ------------------------------------------------------------------ typography
def _opening_context(s, i):
    if i == 0:
        return True
    p = s[i - 1]
    if p == ">":
        k = s.rfind("<", 0, i)
        return not (k != -1 and s[k + 1:k + 2] == "/")
    if p == "\x00":
        return False
    return p.isspace() or p in "([{—–-/“‘"


def smarten(s):
    """Curly quotes and apostrophes, skipping anything inside tags."""
    out, in_tag = [], False
    for i, ch in enumerate(s):
        if ch == "<":
            in_tag = True
        elif ch == ">" and in_tag:
            in_tag = False
            out.append(ch)
            continue
        if in_tag or ch not in "\"'":
            out.append(ch)
            continue
        opening = _opening_context(s, i)
        if ch == '"':
            out.append("“" if opening else "”")
        else:
            nxt = s[i + 1] if i + 1 < len(s) else " "
            out.append("‘" if opening and not nxt.isspace() else "’")
    return "".join(out)


# -------------------------------------------------------------------- context
class Ctx:
    """Knows where a page lives, so links can be absolute (production) or
    relative (file/preview builds, which have no server to resolve /dir/)."""

    def __init__(self, page_path, preview, site, versions):
        self.page_path = page_path            # e.g. "articles/the-audit/index.html"
        self.preview = preview
        self.site = site
        self.versions = versions

    def url(self, href):
        if not href.startswith("/") or href.startswith("//"):
            return href
        if not self.preview:
            return href
        path, _, frag = href.partition("#")
        path, _, query = path.partition("?")
        target = path.lstrip("/")
        if target == "" or target.endswith("/"):
            target += "index.html"
        base = os.path.dirname(self.page_path) or "."
        rel = os.path.relpath(target, base)
        return rel + ("?" + query if query else "") + ("#" + frag if frag else "")

    def asset(self, path):
        v = self.versions.get(path)
        return self.url(path) + (f"?v={v}" if v and not self.preview else "")

    def canonical(self, path):
        return self.site["base_url"] + path


# ------------------------------------------------------------------- markdown
FENCE_RE = re.compile(r"^(:{3,})\s*([A-Za-z][\w-]*)?\s*(.*)$")
ATTR_RE = re.compile(r'([\w-]+)="([^"]*)"')


class Markdown:
    """A deliberately small Markdown subset plus :::directives.
    Supported: ## / ### / #### headings, paragraphs, - and 1. lists,
    > blockquotes, ``` code, **bold**, *italic*, `code`, [links](url),
    {{stat}} tokens, and fenced directives (:::name attr="v" ... :::)."""

    def __init__(self, page, build):
        self.page = page
        self.build = build
        self.ctx = page.ctx
        self.tokens = build.tokens
        self.headings = []
        self.ids = set()
        self.counter = 0

    # blocks -----------------------------------------------------------------
    def render(self, text):
        return "\n".join(self.blocks(text.split("\n")))

    @staticmethod
    def starts_block(s):
        return bool(re.match(r"^(#{2,4}\s|>|[-*]\s|\d+\.\s|```|:{3,}|---$)", s))

    def blocks(self, lines):
        out, i, n = [], 0, len(lines)
        while i < n:
            s = lines[i].strip()
            if not s:
                i += 1
                continue
            m = FENCE_RE.match(s)
            if m and m.group(2):
                fence, name = m.group(1), m.group(2)
                attrs = dict(ATTR_RE.findall(m.group(3) or ""))
                j = i + 1
                while j < n and lines[j].strip() != fence:
                    j += 1
                if j >= n:
                    raise BuildError(f"{self.page.src}: unclosed :::{name}")
                out.append(self.directive(name, attrs, lines[i + 1:j]))
                i = j + 1
                continue
            if s.startswith("```"):
                j = i + 1
                while j < n and not lines[j].strip().startswith("```"):
                    j += 1
                out.append(f"<pre><code>{esc(chr(10).join(lines[i + 1:j]))}</code></pre>")
                i = j + 1
                continue
            hm = re.match(r"^(#{2,4})\s+(.*)$", s)
            if hm:
                out.append(self.heading(len(hm.group(1)), hm.group(2)))
                i += 1
                continue
            if s.startswith(">"):
                buf, j = [], i
                while j < n and lines[j].strip().startswith(">"):
                    buf.append(re.sub(r"^\s*>\s?", "", lines[j]))
                    j += 1
                out.append("<blockquote>" + "\n".join(self.blocks(buf)) + "</blockquote>")
                i = j
                continue
            if re.match(r"^[-*]\s+", s):
                items, i = self.collect_list(lines, i, r"^[-*]\s+")
                out.append("<ul>" + "".join(f"<li>{self.inline(t)}</li>" for t in items) + "</ul>")
                continue
            om = re.match(r"^(\d+)\.\s+", s)
            if om:
                start = int(om.group(1))
                items, i = self.collect_list(lines, i, r"^\d+\.\s+")
                st = "" if start == 1 else f' start="{start}"'
                out.append(f"<ol{st}>" + "".join(f"<li>{self.inline(t)}</li>" for t in items) + "</ol>")
                continue
            if s == "---":
                out.append("<hr>")
                i += 1
                continue
            buf, j = [s], i + 1
            while j < n and lines[j].strip() and not self.starts_block(lines[j].strip()):
                buf.append(lines[j].strip())
                j += 1
            out.append(f"<p>{self.inline(' '.join(buf))}</p>")
            i = j
        return out

    @staticmethod
    def collect_list(lines, i, marker):
        items, n = [], len(lines)
        while i < n:
            s = lines[i].strip()
            if not s:
                k = i + 1
                while k < n and not lines[k].strip():
                    k += 1
                if k < n and re.match(marker, lines[k].strip()):
                    i = k
                    continue
                break
            if re.match(marker, s):
                items.append(re.sub(marker, "", s, count=1))
            elif lines[i][:1] in (" ", "\t") and items:
                items[-1] += " " + s
            else:
                break
            i += 1
        return items, i

    def unique_id(self, base):
        hid, k = base, 2
        while hid in self.ids:
            hid, k = f"{base}-{k}", k + 1
        self.ids.add(hid)
        return hid

    def heading(self, level, raw):
        inner = self.inline(raw)
        hid = self.unique_id(slugify(strip_tags(inner)))
        self.headings.append((level, strip_tags(inner), hid))
        return f'<h{level} id="{hid}">{inner}</h{level}>'

    # inline -----------------------------------------------------------------
    def inline(self, text):
        text = resolve_tokens(text, self.tokens, self.page.src)
        stash = []

        def keep(fragment):
            stash.append(fragment)
            return f"\x00{len(stash) - 1}\x00"

        text = re.sub(r"`([^`]+)`", lambda m: keep(f"<code>{esc(m.group(1))}</code>"), text)
        text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: keep(self.link(m.group(1), m.group(2))), text)
        text = smarten(self.emph(esc(text)))
        return re.sub(r"\x00(\d+)\x00", lambda m: stash[int(m.group(1))], text)

    @staticmethod
    def emph(s):
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        return re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<em>\1</em>", s)

    def link(self, label, href):
        inner = smarten(self.emph(esc(label)))
        external = href.startswith("http")
        rel = ' rel="noopener"' if external else ""
        return f'<a href="{attr(self.ctx.url(href))}"{rel}>{inner}</a>'

    # directives ---------------------------------------------------------------
    def directive(self, name, attrs, inner):
        fn = getattr(self, "d_" + name.replace("-", "_"), None)
        if fn is None:
            raise BuildError(f"{self.page.src}: unknown directive :::{name}")
        self.build.directive_use.setdefault(name, []).append(self.page.path)
        return fn(attrs, inner)

    def d_steps(self, attrs, inner):
        return '<div class="steps">' + "".join(self.blocks(inner)) + "</div>"

    def d_more(self, attrs, inner):
        label = attrs.get("label", "Deep dive")
        return (f'<aside class="more"><p class="more-label">{esc(label)}</p>'
                + "".join(self.blocks(inner)) + "</aside>")

    def d_check(self, attrs, inner):
        self.counter += 1
        cid = f"check-{self.counter}"
        text = " ".join(l.strip() for l in inner if l.strip())
        return (f'<div class="check"><input type="checkbox" id="{cid}">'
                f'<label for="{cid}"><span class="check-kicker">Check yourself</span> '
                f"{self.inline(text)}</label></div>")

    def d_stats(self, attrs, inner):
        return self.build.render_count(self.ctx)

    def d_timeline(self, attrs, inner):
        return self.build.render_timeline()

    def d_compare(self, attrs, inner):
        return '<div class="compare">' + "".join(self.blocks(inner)) + "</div>"

    def d_annotated(self, attrs, inner):
        tone = attrs.get("tone", "bad")
        pairs = []
        for raw in inner:
            s = raw.strip()
            if not s:
                continue
            if s.startswith(">"):
                pairs.append([s[1:].strip(), ""])
            elif not pairs:
                raise BuildError(f"{self.page.src}: annotation before the first > email line")
            else:
                pairs[-1][1] = (pairs[-1][1] + " " + s).strip()
        rows = "".join(
            f'<li class="ann-row"><span class="ann-n" aria-hidden="true">{n}</span>'
            f'<p class="ann-line">{self.inline(line)}</p>'
            f'<p class="ann-note">{self.inline(note)}</p></li>'
            for n, (line, note) in enumerate(pairs, 1))
        icon = ICON["x"] if tone == "bad" else ICON["check"]
        return (f'<section class="ann ann--{attr(tone)}" aria-label="{attr(attrs.get("title", ""))}">'
                f'<header class="ann-head"><p class="ann-title">{esc(attrs.get("title", ""))}</p>'
                f'<p class="ann-source">{esc(attrs.get("source", ""))}</p>'
                f'<p class="ann-verdict">{icon}<span>{esc(attrs.get("verdict", ""))}</span></p></header>'
                f'<ol class="ann-rows">{rows}</ol></section>')

    def d_tool_cards(self, attrs, inner):
        return self.build.render_tool_cards(self.ctx)

    def d_scorer_app(self, attrs, inner):
        return self.build.render_scorer_app(self.ctx)

    def d_scorer_weights(self, attrs, inner):
        return self.build.render_scorer_weights()

    def d_crm_app(self, attrs, inner):
        return self.build.render_crm_app(self.ctx)

    def d_template_download(self, attrs, inner):
        return self.build.render_template_download(self.ctx)

    def d_studio_cta(self, attrs, inner):
        return self.build.render_studio_cta(self.ctx)


# ---------------------------------------------------------------------- pages
class Page:
    def __init__(self, path, src, kind, meta, body_md, ctx):
        self.path = path          # output path relative to the site root
        self.src = src            # source file, for messages
        self.kind = kind
        self.meta = meta
        self.body_md = body_md
        self.ctx = ctx
        self.url = "/" + path[: -len("index.html")] if path.endswith("index.html") else "/" + path


class Build:
    def __init__(self, out_dir, preview=False, inline_fonts=False):
        self.out = Path(out_dir)
        self.preview = preview
        self.inline_fonts = inline_fonts
        self.stats, self.site, self.tokens = load_data()
        self.directive_use = {}
        self.written = []
        self.warnings = []
        self.versions = {}
        for rel in ("/assets/css/site.css", "/assets/js/site.js", "/assets/js/score.js",
                    "/assets/js/scorer.js", "/assets/js/crm.js"):
            f = PUBLIC / rel.lstrip("/")
            if f.exists():
                self.versions[rel] = hashlib.md5(f.read_bytes()).hexdigest()[:8]

    # helpers --------------------------------------------------------------
    def t(self, text, where="template"):
        return resolve_tokens(text, self.tokens, where)

    def ctx(self, path):
        return Ctx(path, self.preview, self.site, self.versions)

    def write(self, rel, content):
        dest = self.out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, "utf-8")
        self.written.append(rel)

    # content ---------------------------------------------------------------
    def load_articles(self):
        problems, articles = [], []
        for f in sorted((CONTENT / "articles").glob("*.md")):
            raw = f.read_text("utf-8")
            problems += lint_hardcoded(raw, self.tokens, f"content/articles/{f.name}")
            meta, body = parse_front_matter(raw, f.name)
            meta = {k: smarten(self.t(v, f.name)) for k, v in meta.items()}
            meta["slug"] = f.stem
            meta["order"] = int(meta.get("order", 99))
            meta["words"] = word_count(self.t(body, f.name))
            meta["minutes"] = max(1, math.ceil(meta["words"] / WPM))
            path = f"articles/{f.stem}/index.html"
            articles.append(Page(path, f"content/articles/{f.name}", "article", meta, body, self.ctx(path)))
        for f in sorted(CONTENT.glob("*.md")) + sorted((CONTENT / "tools").glob("*.md")):
            problems += lint_hardcoded(f.read_text("utf-8"), self.tokens, str(f.relative_to(ROOT)))
        if problems:
            raise BuildError("hardcoded statistics found:\n  " + "\n  ".join(problems))
        articles.sort(key=lambda p: p.meta["order"])
        return articles

    def load_page(self, rel_src, out_path, kind):
        f = CONTENT / rel_src
        meta, body = parse_front_matter(f.read_text("utf-8"), rel_src)
        meta = {k: smarten(self.t(v, rel_src)) for k, v in meta.items()}
        return Page(out_path, f"content/{rel_src}", kind, meta, body, self.ctx(out_path))

    # shared chrome ----------------------------------------------------------
    def head(self, page, title, desc, og_type, og_image, jsonld, scripts=()):
        c = page.ctx
        canonical = c.canonical(page.url)
        full_title = title
        suffix = " · " + self.site["name"]
        if page.kind != "home" and len(title + suffix) <= TITLE_MAX:
            full_title = title + suffix
        if len(full_title) > TITLE_MAX:
            self.warnings.append(f"{page.path}: title is {len(full_title)} chars (> {TITLE_MAX})")
        if len(desc) > DESC_MAX:
            self.warnings.append(f"{page.path}: description is {len(desc)} chars (> {DESC_MAX})")
        og_img = self.site["base_url"] + og_image
        og_title = page.meta.get("og_title") or page.meta.get("title", title)
        robots = "noindex,follow" if page.kind == "404" else "index,follow"
        a = self.site["author"]
        lines = [
            "<!doctype html>",
            f'<html lang="{self.site["lang"]}" data-page="{page.kind}">',
            "<head>",
            '<meta charset="utf-8">',
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
            f"<title>{esc(full_title)}</title>",
            f'<meta name="description" content="{attr(desc)}">',
            f'<meta name="robots" content="{robots}">',
            f'<meta name="author" content="{attr(a["name"])}">',
            f'<link rel="canonical" href="{attr(canonical)}">',
            f'<meta property="og:site_name" content="{attr(self.site["name"])}">',
            f'<meta property="og:type" content="{og_type}">',
            f'<meta property="og:title" content="{attr(og_title)}">',
            f'<meta property="og:description" content="{attr(desc)}">',
            f'<meta property="og:url" content="{attr(canonical)}">',
            f'<meta property="og:image" content="{attr(og_img)}">',
            '<meta property="og:image:width" content="1200">',
            '<meta property="og:image:height" content="630">',
            f'<meta property="og:image:alt" content="{attr(og_title)}">',
            '<meta property="og:locale" content="en_US">',
        ]
        if og_type == "article":
            lines += [
                f'<meta property="article:published_time" content="{page.meta.get("date", self.site["published"])}">',
                f'<meta property="article:author" content="{attr(a["linkedin"])}">',
            ]
        lines += [
            '<meta name="twitter:card" content="summary_large_image">',
            f'<meta name="twitter:title" content="{attr(og_title)}">',
            f'<meta name="twitter:description" content="{attr(desc)}">',
            f'<meta name="twitter:image" content="{attr(og_img)}">',
            '<meta name="theme-color" content="#ffffff" media="(prefers-color-scheme: light)">',
            '<meta name="theme-color" content="#101319" media="(prefers-color-scheme: dark)">',
            f'<link rel="icon" href="{c.url("/favicon.svg")}" type="image/svg+xml">',
        ]
